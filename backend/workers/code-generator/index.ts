export type QualityLevel = 'fast' | 'balanced' | 'premium';

export interface GenerationRequest {
  type: 'theia-extension' | 'godot-scene' | 'worker' | 'component';
  prompt: string;
  quality: QualityLevel;
  context?: Record<string, any>;
}

export interface GenerationResult {
  id: string;
  type: string;
  prompt: string;
  quality: QualityLevel;
  model_used: string;
  tokens_generated: number;
  work_ratio: number;
  code: string;
  files: GeneratedFile[];
  verified: boolean;
  rollback_id?: string;
  created_at: string;
}

export interface GeneratedFile {
  path: string;
  content: string;
  language: string;
}

export interface VerificationResult {
  passed: boolean;
  errors: string[];
  warnings: string[];
  tests_run: number;
  tests_passed: number;
}

