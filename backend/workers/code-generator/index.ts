export class CodeGenerator {
  constructor(
    private ai: any,  // Cloudflare AI binding
    private db: D1Database
  ) {}

  /**
   * Generate code based on request
   */
  async generate(request: GenerationRequest, userId?: string): Promise<GenerationResult> {
    const config = MODEL_CONFIGS[request.quality];
    const id = nanoid();

    // Build the prompt based on type
    const systemPrompt = this.getSystemPrompt(request.type, request.prompt);

    // Call AI
    const response = await this.ai.run(config.model, {
      prompt: systemPrompt,
      max_tokens: config.maxTokens,
      temperature: config.temperature
    });

    // Parse AI response
    let generatedFiles: GeneratedFile[];
    try {
      const parsed = JSON.parse(response.response);
      generatedFiles = parsed.files || [];
    } catch {
      // Fallback: create single file from raw response
      generatedFiles = [{
        path: 'generated.txt',
        content: response.response,
        language: 'text'
      }];
    }

    // Calculate work ratio (estimate based on tokens and quality)
    const work_ratio = config.expectedWorkRatio;

    // Store generation record
    await this.db.prepare(`
      INSERT INTO code_generations (
        id, user_id, prompt, model_used, quality_level,
        tokens_generated, work_ratio, created_at
      ) VALUES (?, ?, ?, ?, ?, ?, ?, datetime('now'))
    `).bind(
      id,
      userId || null,
      request.prompt,
      config.model,
      request.quality,
      response.usage?.total_tokens || 0,
      work_ratio
    ).run();

    // Verify generated code
    const verification = await this.verify(generatedFiles);

    return {
      id,
      type: request.type,
      prompt: request.prompt,
      quality: request.quality,
      model_used: config.model,
      tokens_generated: response.usage?.total_tokens || 0,
      work_ratio,
      code: generatedFiles.map(f => f.content).join('\n\n'),
      files: generatedFiles,
      verified: verification.passed,
      created_at: new Date().toISOString()
    };
  }

  private getSystemPrompt(type: string, prompt: string): string {
    switch (type) {
      case 'theia-extension':
        return buildTheiaExtensionPrompt(prompt);
      case 'godot-scene':
        return buildGodotScenePrompt(prompt);
      case 'worker':
        return buildWorkerPrompt(prompt);
      default:
        return `Generate code for: ${prompt}`;
    }
  }

  /**
   * Verify generated code
   */
  verifyMethod(files: GeneratedFile[]): VerificationResult {
    const errors: string[] = [];
    const warnings: string[] = [];
    let testsRun = 0;
    let testsPassed = 0;

    for (const file of files) {
      // Basic syntax checks
      if (file.language === 'typescript') {
        testsRun++;
        if (file.content.includes('export')) {
          testsPassed++;
        } else {
          warnings.push(`${file.path}: Missing exports`);
        }

        // Check for common errors
        if (file.content.includes('TODO') || file.content.includes('FIXME')) {
          warnings.push(`${file.path}: Contains TODO items`);
        }

        if (file.content.includes('any')) {
          warnings.push(`${file.path}: Uses 'any' type`);
        }
      }

      if (file.language === 'gdscript') {
        testsRun++;
        if (file.content.includes('extends ')) {
          testsPassed++;
        } else {
          errors.push(`${file.path}: Missing extends clause`);
        }
      }

      if (file.language === 'gdscene') {
        testsRun++;
        if (file.content.includes('[gd_scene')) {
          testsPassed++;
        } else {
          errors.push(`${file.path}: Invalid scene format`);
        }
      }
    }

    return {
      passed: errors.length === 0,
      errors,
      warnings,
      tests_run: testsRun,
      tests_passed: testsPassed
    };
  }

  /**
   * Async wrapper for verification (for compatibility)
   */
  async verify(files: GeneratedFile[]): Promise<VerificationResult> {
    return this.verifyMethod(files);
  }

  /**
   * Rollback to previous generation
   */
  async rollback(generationId: string): Promise<GenerationResult | null> {
    const previous = await this.db.prepare(`
      SELECT rollback_id FROM code_generations WHERE id = ?
    `).bind(generationId).first();

    if (!previous || !previous.rollback_id) {
      return null;
    }

    return await this.getGeneration(previous.rollback_id as string);
  }

  /**
   * Get generation record
   */
  async getGeneration(id: string): Promise<GenerationResult | null> {
    const record = await this.db.prepare(`
      SELECT * FROM code_generations WHERE id = ?
    `).bind(id).first();

    if (!record) return null;

    return {
      id: record.id as string,
      type: '',  // Would need to parse from prompt
      prompt: record.prompt as string,
      quality: record.quality_level as QualityLevel,
      model_used: record.model_used as string,
      tokens_generated: record.tokens_generated as number,
      work_ratio: record.work_ratio as number,
      code: '',  // Would need to fetch from storage
      files: [],
      verified: record.verified === 1,
      created_at: record.created_at as string
    };
  }

  /**
   * Get user's generation history
   */
  async getHistory(userId: string, limit = 20): Promise<GenerationResult[]> {
    const records = await this.db.prepare(`
      SELECT * FROM code_generations
      WHERE user_id = ?
      ORDER BY created_at DESC
      LIMIT ?
    `).bind(userId, limit).all();

    return (records.results || []).map((r: any) => ({
      id: r.id,
      type: '',
      prompt: r.prompt,
      quality: r.quality_level,
      model_used: r.model_used,
      tokens_generated: r.tokens_generated,
      work_ratio: r.work_ratio,
      code: '',
      files: [],
      verified: r.verified === 1,
      created_at: r.created_at
    }));
  }
}

