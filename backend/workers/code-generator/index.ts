export interface CodeGeneratorEnv {
  AI: any;
  STUDENT_STATE: D1Database;
  PROJECT_STORAGE: R2Bucket;
}

export async function handleCodeGeneratorRequest(
  request: Request,
  env: CodeGeneratorEnv,
  _ctx: ExecutionContext
): Promise<Response> {
  const url = new URL(request.url);
  const path = url.pathname.replace('/api/v1/generate', '');
  const method = request.method;

  const generator = new CodeGenerator(env.AI, env.STUDENT_STATE);

  // CORS
  if (method === 'OPTIONS') {
    return new Response(null, {
      headers: {
        'Access-Control-Allow-Origin': '*',
        'Access-Control-Allow-Methods': 'GET, POST',
        'Access-Control-Allow-Headers': 'Content-Type, Authorization',
      }
    });
  }

  try {
    // POST /generate - Generate code
    if (path === '/generate' && method === 'POST') {
      const data = await request.json() as GenerationRequest;
      const userId = request.headers.get('X-User-Id') || undefined;

      const result = await generator.generate(data, userId);

      return Response.json(result, { status: 201 });
    }

    // GET /history - Get user's generation history
    if (path === '/history' && method === 'GET') {
      const userId = request.headers.get('X-User-Id');
      if (!userId) {
        return Response.json({ error: 'Missing user ID' }, { status: 401 });
      }

      const limit = url.searchParams.get('limit')
        ? parseInt(url.searchParams.get('limit')!)
        : 20;

      const history = await generator.getHistory(userId, limit);

      return Response.json({ generations: history });
    }

    // POST /verify/:id - Verify a generation
    if (path.match(/\/verify\/[^/]+$/) && method === 'POST') {
      // Get the generation files and verify
      // This is simplified - would need to fetch files from R2
      const verification = await generator.verify([]);

      return Response.json(verification);
    }

    // POST /rollback/:id - Rollback to previous version
    if (path.match(/\/rollback\/[^/]+$/) && method === 'POST') {
      const id = path.split('/').pop()!;

      const previous = await generator.rollback(id);

      if (!previous) {
        return Response.json({ error: 'No previous version found' }, { status: 404 });
      }

      return Response.json(previous);
    }

    return Response.json({ error: 'Not found' }, { status: 404 });

  } catch (error: any) {
    return Response.json({
      error: error.message || 'Internal server error'
    }, { status: 500 });
  }
}
